import { chromium } from 'playwright-core';
import { existsSync } from 'node:fs';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import http from 'node:http';
import { fixture, state, settle } from './helpers.mjs';
const executablePath = process.env.BROWSER_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/usr/bin/chromium', '/usr/bin/google-chrome'].find(existsSync);
assert(executablePath, 'Задайте BROWSER_PATH — путь к Chrome или Edge');
const f = await fixture();
const output = resolve('test-output'); await mkdir(output, { recursive: true });
let browser, pending;
try {
  browser = await chromium.launch({ executablePath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, locale: 'ru-RU' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(f.base); await page.locator('#empty').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#choose').isEnabled(), true);
  await page.getByRole('radio', { name: 'Онлайн', exact: true }).check();
  await page.reload(); await page.locator('#empty').waitFor();
  assert.equal(await page.getByRole('radio', { name: 'Онлайн', exact: true }).isChecked(), true);
  assert.match(await page.locator('#privacy').innerText(), /аудио и расшифровка отправляются/);
  if ((await state(f.base)).local.available) {
    await page.getByRole('radio', { name: 'Локально', exact: true }).check();
    assert.match(await page.locator('#privacy').innerText(), /только расшифровка/);
  }
  await page.screenshot({ path: resolve(output, 'desktop-empty.png'), fullPage: true });
  await page.locator('#file').setInputFiles({ name: 'wrong.txt', mimeType: 'text/plain', buffer: Buffer.from('wrong') });
  await page.getByRole('alert').filter({ hasText: 'Формат файла не поддерживается' }).waitFor();
  await page.locator('#file').setInputFiles({ name: '<img src=x onerror=alert(1)>.mp4', mimeType: 'video/mp4', buffer: Buffer.from('corrupt') });
  await page.locator('.badge.error').waitFor({ timeout: 20000 });
  await page.locator('.meeting > summary').click();
  await page.getByText('Не удалось прочитать запись.', { exact: false }).waitFor();
  assert.equal(await page.locator('.meeting img').count(), 0);
  assert.equal(await page.locator('#choose').isEnabled(), true);
  await page.reload(); await page.locator('.badge.error').waitFor();
  assert.equal(await page.locator('.meeting').count(), 1);
  pending = http.request(f.base + '/api/meetings', { method: 'POST', headers: { 'X-Meeting-Upload': '1', 'X-File-Name': 'pending.mp4' } });
  pending.on('error', () => {}); pending.write('pending');
  await page.locator('#activity').waitFor();
  assert.equal(await page.locator('#choose').isDisabled(), true);
  assert.equal(await page.getByRole('radio', { name: 'Онлайн', exact: true }).isDisabled(), true);
  await page.reload(); await page.locator('#activity').waitFor();
  assert.equal(await page.locator('.meeting').count(), 2);
  await page.screenshot({ path: resolve(output, 'desktop-processing.png'), fullPage: true });
  const id = (await state(f.base)).meetings[0].id; pending.destroy(); await settle(f.base, id);
  await page.locator('#activity').waitFor({ state: 'hidden' });
  await page.locator('.meeting > summary').first().click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(output, 'mobile-error.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  if ((await state(f.base)).local.available && existsSync(resolve('test-output/real-2min.mp4'))) {
    await page.getByRole('radio', { name: 'Локально', exact: true }).check();
    await page.locator('#auto-transcribe').uncheck();
    await page.locator('#auto-summary').uncheck();
    await page.locator('#file').setInputFiles(resolve('test-output/real-2min.mp4'));
    const card = page.locator('.meeting').filter({ hasText: 'real-2min.mp4' });
    await card.locator('.badge.uploaded').waitFor({ timeout: 20000 });
    await card.locator(':scope > summary').click();
    assert.equal(await card.locator('.stage-summary button').isDisabled(), true);
    await card.locator('.stage-transcription button').click();
    await card.locator('.badge.transcribed').waitFor({ timeout: 60000 });
    await page.reload(); await card.locator('.badge.transcribed').waitFor();
    assert.equal(await page.locator('#auto-transcribe').isChecked(), false);
    assert.equal(await page.locator('#auto-summary').isChecked(), false);
    await card.locator(':scope > summary').click();
    await card.locator('.transcript > summary').click();
    assert((await card.locator('.transcript p').allInnerTexts()).join(' ').length > 100);
    assert(await card.locator('.transcript-meta').count() > 0);
    assert.match(await card.locator('.timecode').first().innerText(), /\d{2}:\d{2}:\d{2}\.\d{3}/);
    const downloadEvent = page.waitForEvent('download');
    await card.getByRole('link', { name: 'Скачать текст встречи (.txt)', exact: true }).click();
    const downloaded = await downloadEvent;
    await downloaded.saveAs(resolve(output, 'browser-meeting.txt'));
    const exported = await readFile(resolve(output, 'browser-meeting.txt'), 'utf8');
    assert.match(exported, /ПОЛНАЯ РАСШИФРОВКА/);
    for (const text of await card.locator('.transcript p').allInnerTexts()) assert(exported.replace(/\s+/g, ' ').includes(text.replace(/\s+/g, ' ')));
    assert.equal((await state(f.base)).meetings[0].transcriptionMode, 'local');
    await card.locator('.stage-summary button').click();
    await card.locator('.badge.error').waitFor(); // Only summary needs a key.
    await page.locator('#usage-panel > summary').click();
    await page.getByRole('cell', { name: 'Не используются', exact: true }).waitFor();
    await page.screenshot({ path: resolve(output, 'mobile-local-transcript.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.screenshot({ path: resolve(output, 'desktop-local-transcript.png'), fullPage: true });
    page.once('dialog', dialog => dialog.accept());
    await card.getByRole('button', { name: 'Удалить файл', exact: true }).click();
    await card.getByText('Исходный файл удалён или недоступен', { exact: true }).waitFor();
    assert((await card.locator('.transcript p').allInnerTexts()).join(' ').length > 100);
    assert.equal((await state(f.base)).meetings[0].sourceAvailable, false);
    page.once('dialog', dialog => dialog.accept());
    await card.getByRole('button', { name: 'Удалить встречу', exact: true }).click();
    await card.waitFor({ state: 'detached' });
    assert.equal(await page.getByRole('cell', { name: 'Не используются', exact: true }).count(), 1);
  }
  assert.deepEqual(errors, []);
  console.log('Браузер: ручные этапы, сохранение настроек, журнал, удаление файла/встречи, безопасный текст, 1440/390 px — пройдено.');
} finally { pending?.destroy(); await browser?.close(); await f.cleanup(); }
